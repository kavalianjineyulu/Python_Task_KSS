def add(a,b,c):
    return(a+b+c)
def multi(a,b,c):
    return(a*b*c)
print("addition:",add(1,2,3))
print("multiplication",multi(1,2,3))

def uppercase(text):
    return text.upper()
def count_characters(text):
    return len(text)

text="hello python"

print("uppercase:",uppercase(text))
print("Character count:",count_characters(text))

